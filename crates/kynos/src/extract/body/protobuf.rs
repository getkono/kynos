//! The `application/protobuf` body codec.
//!
//! Kynos owns the contract, [`Message`], and compiles no protobuf
//! implementation: the application's own generated messages implement it,
//! through `#[derive(ProtobufMessage)]` over the `prost` the application
//! already depends on.

use bytes::Bytes;

use crate::{
    error::rejection::BodyRejection,
    extract::{
        FromRequest,
        body::codec::DecodeError,
        describe::{Describe, RequestContent},
    },
    http::{Parts, body::Body},
    router::operation::OperationCx,
    schema::{Schema, constraints::Pointer, registry::Registry},
};

/// A Protocol Buffers message a [`Protobuf<T>`] body carries.
///
/// The two conversions between a message and its wire bytes, and nothing
/// else: the media type, the body limit, the 400/422 split and the bounds
/// `T`'s schema declares stay Kynos's, as they do for a
/// [`BodyCodec`](super::codec::BodyCodec).
///
/// Derived rather than written. `#[derive(ProtobufMessage)]` (with the
/// `macros` feature) implements it by calling the application's own `prost`,
/// so the protobuf implementation is the one the application's graph resolves
/// and Kynos never names it:
///
/// ```
/// # #[cfg(feature = "macros")]
/// # {
/// use kynos::extract::body::protobuf::{Message, Protobuf};
///
/// #[derive(Clone, PartialEq, prost::Message, kynos::ProtobufMessage, kynos::Schema)]
/// struct Reading {
///     #[prost(uint64, tag = "1")]
///     value: u64,
/// }
///
/// // Field 1, varint wire type, value 7: the whole message.
/// assert_eq!(Reading { value: 7 }.encode(), [0x08, 0x07]);
///
/// async fn store(Protobuf(reading): Protobuf<Reading>) -> Protobuf<Reading> {
///     Protobuf(reading)
/// }
/// # }
/// ```
///
/// Code generated by `prost-build` adds the derive to every message with
/// `config.type_attribute(".", "#[derive(kynos::ProtobufMessage)]")`.
///
/// # What the application's graph decides
///
/// Since Kynos compiles no protobuf implementation, every property of the one
/// that decodes is the application's. Among them is the nesting limit a
/// malicious body is decoded under: `prost` refuses a message nested past 100
/// levels, unless any crate in the application's graph enables its
/// `no-recursion-limit` feature, which removes the limit for every decoder in
/// that build.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a protobuf message Kynos can carry",
    label = "not a `kynos::extract::body::protobuf::Message`",
    note = "derive it beside the protobuf derive: `#[derive(prost::Message, kynos::ProtobufMessage)]`"
)]
pub trait Message: Sized {
    /// Reads a whole request body, which Kynos has already held to
    /// `application/protobuf`, the body limit and the absence of a content
    /// coding.
    ///
    /// Handed the `Bytes` the framework read, so a body arriving as one frame
    /// reaches the decoder without a copy.
    ///
    /// # Errors
    ///
    /// [`DecodeError::Syntax`] for bytes that are not a valid message, which
    /// rejects with 400, and [`DecodeError::Data`] for a valid message that
    /// does not fit `Self`, which rejects with 422 at the root pointer.
    fn decode(bytes: Bytes) -> Result<Self, DecodeError>;

    /// Writes the message as a response body.
    ///
    /// Encoding a protobuf message cannot fail, so neither can this. Return a
    /// vector whose capacity is its length, as `prost`'s `encode_to_vec`
    /// does: the response takes it without a copy, and a spare capacity costs
    /// it an allocation.
    fn encode(&self) -> Vec<u8>;
}

/// An `application/protobuf` request or response body.
///
/// Requires the `protobuf` feature. A missing or different content type
/// rejects with 415 and an invalid protobuf message rejects with 400, while a
/// message that decodes but breaks a bound `T`'s schema declares rejects with
/// 422, keyed by the JSON Pointer of each member that broke one under the
/// name the description gives it. Which bounds are enforced is
/// [`constraints`](crate::schema::constraints)' to say.
///
/// Extracting one therefore requires `T: Schema` as well as `T: Message`, as
/// every codec that decodes a `Schema` type does.
///
/// ```no_run
/// # #[cfg(feature = "protobuf")]
/// # {
/// use kynos::extract::body::protobuf::Protobuf;
///
/// async fn echo<T>(Protobuf(message): Protobuf<T>) -> Protobuf<T> {
///     Protobuf(message)
/// }
/// # }
/// ```
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Protobuf<T>(pub T);

/// The media type decoded, described and written by the response half.
pub(crate) const MEDIA_TYPE: &str = "application/protobuf";

/// `T: Schema` because the bounds a derived field declares are checked once `T`
/// is decoded.
impl<C: Sync, T: Message + Schema + Send> FromRequest<C> for Protobuf<T> {
    type Rejection = BodyRejection;

    async fn from_request(
        parts: &mut Parts,
        body: Body,
        _context: &C,
    ) -> Result<Self, Self::Rejection> {
        let bytes = super::read_body(parts, body, MEDIA_TYPE).await?;
        let value = T::decode(bytes).map_err(super::codec::rejection)?;
        super::checked(value, Pointer::root()).map(Self)
    }
}

impl<T: Schema> Describe for Protobuf<T> {
    fn describe(operation: &mut OperationCx<'_>) {
        super::describe_body::<Self>(operation);
    }
}

impl<T: Schema> RequestContent for Protobuf<T> {
    fn media_types() -> Vec<&'static str> {
        vec![MEDIA_TYPE]
    }

    fn request_body(registry: &mut Registry) -> kynos_openapi::RequestBody {
        kynos_openapi::RequestBody::new(
            MEDIA_TYPE,
            kynos_openapi::MediaType::new(registry.resolve::<T>()),
        )
    }

    fn constraint_types() -> Vec<&'static str> {
        super::constraint_type::<T>()
    }
}
